import React, { useState } from 'react';
import {
  Mail, X, Send, Building2, User, MessageSquare, Paperclip, CheckCircle2, AlertTriangle, ShieldAlert, ChevronDown, Copy, Check, Zap
} from 'lucide-react';
import { AccountNode, Scenario } from '../types';

interface EmailReportModalProps {
  isOpen: boolean;
  onClose: () => void;
  scenario: Scenario;
  selectedNode: AccountNode | null;
}

type EmailMode = 'INTERNAL' | 'GMAIL';

const INTERNAL_RECIPIENTS = [
  { label: 'AML Compliance Team', address: 'aml-compliance@apexbank.com' },
  { label: 'FinCEN Liaison Office', address: 'fincen-liaison@apexbank.com' },
  { label: 'Senior Fraud Investigations', address: 'fraud-investigations@apexbank.com' },
  { label: 'Regulatory Reporting Unit', address: 'regulatory-reporting@apexbank.com' },
  { label: 'CISO Office (Critical)', address: 'ciso@apexbank.com' },
];

export const EmailReportModal: React.FC<EmailReportModalProps> = ({
  isOpen, onClose, scenario, selectedNode
}) => {
  const target = selectedNode || scenario.nodes.find(n => n.riskScore > 80) || scenario.nodes[0];
  const [emailMode, setEmailMode] = useState<EmailMode>('INTERNAL');
  const [selectedRecipient, setSelectedRecipient] = useState(INTERNAL_RECIPIENTS[0].address);
  const [customEmail, setCustomEmail] = useState('');
  const [cc, setCc] = useState('');
  const [priority, setPriority] = useState<'HIGH' | 'URGENT' | 'NORMAL'>('HIGH');
  const [includeAttachment, setIncludeAttachment] = useState(true);
  const [sent, setSent] = useState(false);
  const [sending, setSending] = useState(false);
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const subject = `[${priority}] AML Alert: Suspicious Account ${target.accountNumber} — Risk Score ${target.riskScore}/100`;

  const body = `Dear Compliance Team,

This is an automated AML surveillance alert from the Apex Commercial Bank Mule Account Detection System.

━━━━━━━━━━━━━━━━━━━━━━━━━━━
FLAGGED ACCOUNT DETAILS
━━━━━━━━━━━━━━━━━━━━━━━━━━━
Account Holder: ${target.name}
Account Number: ${target.accountNumber}
Bank / Branch: ${target.bank} (${target.country})
Mule Classification: ${target.muleType}
Risk Score: ${target.riskScore}/100 [${target.riskTier}]
KYC Status: ${target.kycTier}

KEY RISK INDICATORS
━━━━━━━━━━━━━━━━━━━━━━━━━━━
• Betweenness Centrality: ${target.betweennessCentrality.toFixed(3)} (network bridge)
• Drain Latency: ${target.drainLatencySeconds}s (near-instant fund forwarding)
• Inflow/Outflow Rate: ${(target.inflowOutflowRatio * 100).toFixed(1)}% evacuation
• Velocity Score: ${target.velocityScore}/100
• Dormancy-Burst Days: ${target.dormantDaysPriorToBurst}
• PageRank: ${target.pageRank.toFixed(4)}

Case Scenario: ${scenario.title}
Total Network Volume: $${scenario.summary.totalVolume.toLocaleString()} USD
Flagged Volume: $${scenario.summary.flaggedVolume.toLocaleString()} USD
${includeAttachment ? '\n[ATTACHMENT: SAR-FINCEN-2026-DRAFT.pdf attached]\n' : ''}
Please review and take appropriate action within 24 hours per BSA/AML policy.

Generated by: AEGIS AML Surveillance Intelligence Platform
Apex Commercial Bank — Regulatory Sandbox
Timestamp: ${new Date().toISOString()}`;

  const gmailLink = `https://mail.google.com/mail/?view=cm&fs=1&to=${encodeURIComponent(customEmail || 'compliance@apexbank.com')}&su=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
  const mailtoLink = `mailto:${customEmail || selectedRecipient}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;

  const handleSendInternal = () => {
    setSending(true);
    setTimeout(() => {
      setSending(false);
      setSent(true);
    }, 1800);
  };

  const handleCopyBody = () => {
    navigator.clipboard.writeText(body);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleClose = () => {
    setSent(false);
    setSending(false);
    onClose();
  };

  if (sent) {
    return (
      <div className="fixed inset-0 z-50 bg-black/40 backdrop-blur-sm flex items-center justify-center p-4">
        <div className="bg-white rounded-2xl border border-slate-200 shadow-2xl p-10 max-w-sm w-full text-center">
          <div className="w-16 h-16 rounded-full bg-emerald-100 border-2 border-emerald-300 flex items-center justify-center mx-auto mb-4">
            <CheckCircle2 className="w-8 h-8 text-emerald-600" />
          </div>
          <h3 className="text-lg font-bold text-slate-900 font-mono">Report Sent!</h3>
          <p className="text-sm text-slate-500 mt-2">
            AML alert for <span className="font-semibold text-slate-800">{target.name}</span> has been dispatched to <span className="font-mono text-emerald-700">{selectedRecipient}</span>.
          </p>
          <p className="text-xs text-slate-400 mt-2 font-mono">Ref: AEGIS-{Date.now().toString().slice(-8)}</p>
          <button onClick={handleClose} className="mt-6 w-full py-2.5 bg-emerald-600 text-white rounded-xl text-sm font-semibold hover:bg-emerald-700 transition-colors">Close</button>
        </div>
      </div>
    );
  }

  return (
    <div className="fixed inset-0 z-50 bg-black/40 backdrop-blur-sm flex items-center justify-center p-4">
      <div className="bg-white rounded-2xl border border-slate-200 shadow-2xl w-full max-w-2xl max-h-[90vh] flex flex-col">

        {/* Header */}
        <div className="flex items-center gap-3 px-6 py-4 border-b border-slate-100 bg-slate-50 rounded-t-2xl">
          <div className="w-9 h-9 rounded-xl bg-blue-100 border border-blue-200 flex items-center justify-center">
            <Mail className="w-5 h-5 text-blue-700" />
          </div>
          <div>
            <h2 className="text-sm font-bold text-slate-900 font-mono">Email AML Report</h2>
            <p className="text-xs text-slate-500">Send SAR alert to internal team or external Gmail</p>
          </div>
          <button onClick={handleClose} className="ml-auto p-1.5 rounded-lg hover:bg-slate-200 text-slate-500">
            <X className="w-4 h-4" />
          </button>
        </div>

        <div className="flex-1 overflow-y-auto p-6 space-y-4">

          {/* Mode Toggle */}
          <div className="flex gap-2">
            <button
              onClick={() => setEmailMode('INTERNAL')}
              className={`flex-1 flex items-center justify-center gap-2 py-2.5 rounded-xl border text-xs font-semibold transition-all ${
                emailMode === 'INTERNAL' ? 'bg-blue-50 border-blue-300 text-blue-800' : 'bg-slate-50 border-slate-200 text-slate-600 hover:border-blue-200'
              }`}
            >
              <Building2 className="w-3.5 h-3.5" /> Internal Org Email
            </button>
            <button
              onClick={() => setEmailMode('GMAIL')}
              className={`flex-1 flex items-center justify-center gap-2 py-2.5 rounded-xl border text-xs font-semibold transition-all ${
                emailMode === 'GMAIL' ? 'bg-red-50 border-red-300 text-red-800' : 'bg-slate-50 border-slate-200 text-slate-600 hover:border-red-200'
              }`}
            >
              <Mail className="w-3.5 h-3.5 text-red-500" /> Gmail / External
            </button>
          </div>

          {/* Flagged Account Badge */}
          <div className="flex items-center gap-3 p-3 rounded-xl bg-red-50 border border-red-200">
            <AlertTriangle className="w-4 h-4 text-red-600 flex-shrink-0" />
            <div>
              <p className="text-xs font-bold text-red-800 font-mono">{target.name} ({target.accountNumber})</p>
              <p className="text-[10px] text-red-600">{target.muleType} · Risk Score: {target.riskScore}/100 · {target.riskTier}</p>
            </div>
          </div>

          {/* Recipient */}
          {emailMode === 'INTERNAL' ? (
            <div>
              <label className="block text-xs font-semibold text-slate-700 font-mono mb-1.5">To (Internal Department)</label>
              <div className="relative">
                <select
                  value={selectedRecipient}
                  onChange={e => setSelectedRecipient(e.target.value)}
                  className="w-full px-3 py-2.5 pr-8 border border-slate-200 rounded-xl text-xs bg-white text-slate-800 font-mono appearance-none focus:ring-2 focus:ring-blue-200 focus:border-blue-400 outline-none"
                >
                  {INTERNAL_RECIPIENTS.map(r => (
                    <option key={r.address} value={r.address}>{r.label} — {r.address}</option>
                  ))}
                </select>
                <ChevronDown className="absolute right-3 top-3 w-3.5 h-3.5 text-slate-400 pointer-events-none" />
              </div>
            </div>
          ) : (
            <div>
              <label className="block text-xs font-semibold text-slate-700 font-mono mb-1.5">To (Gmail / External)</label>
              <input
                type="email"
                value={customEmail}
                onChange={e => setCustomEmail(e.target.value)}
                placeholder="recipient@gmail.com"
                className="w-full px-3 py-2.5 border border-slate-200 rounded-xl text-xs font-mono focus:ring-2 focus:ring-red-200 focus:border-red-400 outline-none"
              />
            </div>
          )}

          {/* CC */}
          <div>
            <label className="block text-xs font-semibold text-slate-700 font-mono mb-1.5">CC (optional)</label>
            <input
              type="text"
              value={cc}
              onChange={e => setCc(e.target.value)}
              placeholder="cc@apexbank.com, supervisor@apexbank.com"
              className="w-full px-3 py-2.5 border border-slate-200 rounded-xl text-xs font-mono focus:ring-2 focus:ring-blue-200 focus:border-blue-400 outline-none"
            />
          </div>

          {/* Priority + Attachment */}
          <div className="flex gap-3">
            <div className="flex-1">
              <label className="block text-xs font-semibold text-slate-700 font-mono mb-1.5">Priority</label>
              <div className="relative">
                <select
                  value={priority}
                  onChange={e => setPriority(e.target.value as typeof priority)}
                  className="w-full px-3 py-2.5 pr-8 border border-slate-200 rounded-xl text-xs font-mono appearance-none bg-white focus:ring-2 focus:ring-blue-200 outline-none"
                >
                  <option value="NORMAL">NORMAL</option>
                  <option value="HIGH">HIGH</option>
                  <option value="URGENT">URGENT</option>
                </select>
                <ChevronDown className="absolute right-3 top-3 w-3.5 h-3.5 text-slate-400 pointer-events-none" />
              </div>
            </div>
            <div className="flex-1 flex flex-col">
              <label className="block text-xs font-semibold text-slate-700 font-mono mb-1.5">Attach SAR Draft</label>
              <label className="flex-1 flex items-center gap-2 px-3 py-2.5 border border-slate-200 rounded-xl cursor-pointer hover:bg-slate-50 transition-colors">
                <input type="checkbox" checked={includeAttachment} onChange={e => setIncludeAttachment(e.target.checked)} className="accent-emerald-600" />
                <span className="text-xs font-mono text-slate-700">SAR-FINCEN-DRAFT.pdf</span>
                <Paperclip className="w-3.5 h-3.5 text-slate-400 ml-auto" />
              </label>
            </div>
          </div>

          {/* Subject */}
          <div>
            <label className="block text-xs font-semibold text-slate-700 font-mono mb-1.5">Subject</label>
            <div className="px-3 py-2.5 border border-slate-100 rounded-xl bg-slate-50 text-xs font-mono text-slate-600 select-all">{subject}</div>
          </div>

          {/* Body Preview */}
          <div>
            <div className="flex items-center justify-between mb-1.5">
              <label className="text-xs font-semibold text-slate-700 font-mono">Email Body Preview</label>
              <button onClick={handleCopyBody} className="flex items-center gap-1 text-[11px] text-slate-500 hover:text-slate-800 font-mono">
                {copied ? <Check className="w-3 h-3 text-emerald-600" /> : <Copy className="w-3 h-3" />}
                {copied ? 'Copied!' : 'Copy'}
              </button>
            </div>
            <textarea
              readOnly
              value={body}
              rows={8}
              className="w-full px-3 py-2.5 border border-slate-200 rounded-xl text-[10px] font-mono text-slate-600 bg-slate-50 resize-none focus:outline-none"
            />
          </div>
        </div>

        {/* Footer Actions */}
        <div className="flex items-center gap-3 px-6 py-4 border-t border-slate-100 bg-slate-50 rounded-b-2xl">
          <button onClick={handleClose} className="px-5 py-2 rounded-xl border border-slate-200 text-sm text-slate-600 hover:bg-slate-100 font-semibold transition-colors">Cancel</button>

          {emailMode === 'GMAIL' ? (
            <a
              href={gmailLink}
              target="_blank"
              rel="noopener noreferrer"
              className="flex-1 flex items-center justify-center gap-2 py-2.5 rounded-xl bg-red-600 hover:bg-red-700 text-white text-sm font-bold transition-colors"
            >
              <Mail className="w-4 h-4" />
              Open in Gmail
            </a>
          ) : (
            <button
              onClick={handleSendInternal}
              disabled={sending}
              className="flex-1 flex items-center justify-center gap-2 py-2.5 rounded-xl bg-blue-700 hover:bg-blue-800 text-white text-sm font-bold transition-colors disabled:opacity-60"
            >
              {sending ? (
                <><Zap className="w-4 h-4 animate-pulse" /> Sending…</>
              ) : (
                <><Send className="w-4 h-4" /> Send Internal Report</>
              )}
            </button>
          )}

          <a
            href={mailtoLink}
            className="px-4 py-2.5 rounded-xl border border-slate-300 text-sm text-slate-700 hover:bg-slate-100 font-semibold transition-colors"
          >
            Open Email App
          </a>
        </div>
      </div>
    </div>
  );
};
